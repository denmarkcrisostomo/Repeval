import { join } from 'node:path';
import { rel, VERSION, type Paths } from '../core/paths.js';
import type { GeneratedFile, Plan } from '../core/types.js';

export function slugForRoute(route: string): string {
  if (route === '/') return 'home';
  return route.replace(/^\//, '').replace(/[^a-z0-9]+/gi, '-').replace(/^-|-$/g, '').toLowerCase() || 'page';
}

const q = (s: string) => JSON.stringify(s);

const CONFIG = `// Generated by Repeval ${VERSION}. Paths come from environment variables set by \`repeval test\`.
import { defineConfig, devices } from '@playwright/test';

const PORT = Number(process.env.REPEVAL_PORT ?? 3000);

export default defineConfig({
  testDir: '.',
  outputDir: process.env.REPEVAL_PW_OUTPUT ?? '../results/playwright',
  timeout: 30_000,
  workers: 2,
  reporter: [['list'], ['json', { outputFile: process.env.REPEVAL_E2E_JSON ?? '../results/e2e.json' }]],
  use: {
    baseURL: \`http://localhost:\${PORT}\`,
    trace: 'retain-on-failure',
    video: 'retain-on-failure',
    screenshot: 'only-on-failure',
  },
  projects: [{ name: 'chromium', use: { ...devices['Desktop Chrome'] } }],
  webServer: process.env.REPEVAL_START
    ? {
        command: process.env.REPEVAL_START,
        cwd: process.env.REPEVAL_ROOT,
        url: \`http://localhost:\${PORT}\`,
        reuseExistingServer: !process.env.CI,
        timeout: 120_000,
        env: { PORT: String(PORT) },
      }
    : undefined,
});
`;

const PAGE_HELPER = `// Generated by Repeval ${VERSION}. Opens a page, collects browser errors and takes step screenshots.
import type { Page } from '@playwright/test';

const SHOTS = process.env.REPEVAL_SHOTS ?? 'shots';

export async function openPage(page: Page, route: string, slug: string) {
  const errors: string[] = [];
  page.on('pageerror', (e) => errors.push(\`Uncaught error: \${e.message}\`));
  page.on('console', (m) => {
    if (m.type() === 'error') errors.push(\`Console error: \${m.text()}\`);
  });
  const response = await page.goto(route, { waitUntil: 'load' });
  await page.waitForLoadState('networkidle', { timeout: 5_000 }).catch(() => {});
  let step = 0;
  const screenshot = async (name: string) => {
    step += 1;
    await page.screenshot({ path: \`\${SHOTS}/\${slug}/\${String(step).padStart(2, '0')}-\${name}.png\`, fullPage: true });
  };
  return { response, errors, screenshot };
}
`;

export function generateE2E(plan: Plan, p: Paths): { files: GeneratedFile[]; contents: Map<string, string> } {
  const pages = plan.targets.filter((t) => t.type === 'e2e' && t.enabled);
  const apis = plan.targets.filter((t) => t.type === 'api' && t.enabled);
  const contents = new Map<string, string>();
  const files: GeneratedFile[] = [];
  if (pages.length === 0 && apis.length === 0) return { files, contents };

  const add = (name: string, text: string, kind: GeneratedFile['kind'], targets: string[]) => {
    const path = join(p.e2eDir, name);
    contents.set(path, text);
    files.push({ path: rel(p.root, path), kind, framework: 'playwright', targets });
  };

  add('playwright.config.ts', CONFIG, 'config', []);

  if (pages.length) {
    add('_repeval.ts', PAGE_HELPER, 'helper', []);
    const tests = pages.map((t) => {
      const route = t.target;
      return `test(${q(`page ${route} loads`)}, { annotation: { type: 'repeval-target', description: ${q(t.id)} } }, async ({ page }) => {
  const { response, errors, screenshot } = await openPage(page, ${q(route)}, ${q(slugForRoute(route))});
  await screenshot('desktop');
  await page.setViewportSize({ width: 390, height: 844 });
  await screenshot('mobile');

  expect(response?.status() ?? 0, 'HTTP status').toBeLessThan(400);
  await expect(page.locator('body'), 'page has visible content').not.toBeEmpty();
  expect(errors, \`browser errors on this page: \${errors.join(' | ')}\`).toEqual([]);
});`;
    });
    add(
      'pages.spec.ts',
      `// Generated by Repeval ${VERSION} (template writer, no AI).
// Smoke test for every page: it loads, shows content, has no browser errors. Screenshots at desktop and mobile width.
import { expect, test } from '@playwright/test';
import { openPage } from './_repeval';

${tests.join('\n\n')}
`,
      'e2e',
      pages.map((t) => t.id),
    );
  }

  if (apis.length) {
    const tests = apis.map((t) => {
      const [method, path] = t.target.split(' ');
      return `test(${q(`${method} ${path} responds`)}, { annotation: { type: 'repeval-target', description: ${q(t.id)} } }, async ({ request }) => {
  const res = await request.${method.toLowerCase()}(${q(path)});
  expect(res.status(), 'HTTP status (5xx means the server failed)').toBeLessThan(500);
});`;
    });
    add(
      'api.spec.ts',
      `// Generated by Repeval ${VERSION} (template writer, no AI).
// Checks that each simple GET endpoint answers without a server error.
import { expect, test } from '@playwright/test';

${tests.join('\n\n')}
`,
      'api',
      apis.map((t) => t.id),
    );
  }

  return { files, contents };
}
