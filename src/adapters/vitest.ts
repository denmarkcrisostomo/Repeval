import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { importPath, rel, VERSION, type Paths } from '../core/paths.js';
import type { Analysis, FunctionInfo, GeneratedFile, Plan } from '../core/types.js';

const HELPER = `// Generated by Repeval ${VERSION}. Shared helpers for baseline tests.
import { expect } from 'vitest';
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const BASELINES = process.env.REPEVAL_BASELINES ?? '.repeval/baselines';
const EVENTS = process.env.REPEVAL_EVENTS;
const UPDATE = process.env.REPEVAL_UPDATE === '1';

/** Call fn and describe what happened in a JSON-safe way (value or thrown error). */
export function run(fn: () => unknown): unknown {
  try {
    return { returned: serialize(fn()) };
  } catch (e) {
    return { threw: e instanceof Error ? \`\${e.name}: \${e.message}\` : String(e) };
  }
}

function serialize(v: unknown, seen = new WeakSet<object>(), depth = 0): unknown {
  if (v === undefined) return '[undefined]';
  if (typeof v === 'number') return Number.isFinite(v) ? v : String(v);
  if (typeof v === 'bigint') return \`\${v}n\`;
  if (typeof v === 'function') return '[function]';
  if (typeof v === 'symbol') return v.toString();
  if (v === null || typeof v !== 'object') return v;
  if (seen.has(v)) return '[circular]';
  if (depth > 6) return '[deep]';
  seen.add(v);
  if (v instanceof Date) return \`[Date \${Number.isNaN(v.getTime()) ? 'Invalid' : v.toISOString()}]\`;
  if (v instanceof Map) return { '[Map]': [...v.entries()].map((e) => serialize(e, seen, depth + 1)) };
  if (v instanceof Set) return { '[Set]': [...v.values()].map((e) => serialize(e, seen, depth + 1)) };
  if (Array.isArray(v)) return v.map((e) => serialize(e, seen, depth + 1));
  const out: Record<string, unknown> = {};
  for (const [k, val] of Object.entries(v)) out[k] = serialize(val, seen, depth + 1);
  return out;
}

/** First run records the results; later runs must match them. */
export function matchBaseline(key: string, value: unknown): void {
  const file = join(BASELINES, key + '.json');
  const record = (status: string) => EVENTS && appendFileSync(EVENTS, JSON.stringify({ key, status }) + '\\n');
  if (UPDATE || !existsSync(file)) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, JSON.stringify(value, null, 2) + '\\n');
    record('recorded');
    return;
  }
  const previous = JSON.parse(readFileSync(file, 'utf8'));
  const same = JSON.stringify(previous) === JSON.stringify(value);
  record(same ? 'matched' : 'changed');
  expect(value, 'Results changed since the recorded baseline').toEqual(previous);
}
`;

function testFileName(sourceFile: string): string {
  return sourceFile.replace(/\.[^./]+$/, '').replace(/[\\/]/g, '__') + '.test.ts';
}

function accessor(f: FunctionInfo): string {
  return f.exportName === 'default' ? 'mod.default' : `mod.${f.exportName}`;
}

function q(s: string): string {
  return JSON.stringify(s);
}

function functionBlock(f: FunctionInfo): string {
  const title = f.exportName === 'default' ? `${f.name}() (default export)` : `${f.exportName}()`;
  const lines = [
    `  describe(${q(title)}, () => {`,
    `    it('is exported as a function', () => {`,
    `      expect(typeof ${accessor(f)}).toBe('function');`,
    `    });`,
  ];
  if (f.callable) {
    lines.push(
      '',
      `    it('returns the same results as the recorded baseline', () => {`,
      `      const fn = ${accessor(f)} as (...args: any[]) => unknown;`,
      `      const results = [`,
      ...f.cases.map((c) => `        { args: ${q(c.join(', '))}, result: run(() => fn(${c.join(', ')})) },`),
      `      ];`,
      `      matchBaseline(${q(`${f.file}/${f.exportName}`)}, results);`,
      `    });`,
    );
  }
  lines.push('  });');
  return lines.join('\n');
}

/** tsconfig "paths" -> Vite aliases, so `@/lib/x` imports keep working in generated tests. */
function tsconfigAliases(root: string): Record<string, string> {
  const file = join(root, 'tsconfig.json');
  if (!existsSync(file)) return {};
  try {
    const text = readFileSync(file, 'utf8')
      .replace(/\/\*[\s\S]*?\*\//g, '')
      .replace(/^\s*\/\/.*$/gm, '')
      .replace(/,(\s*[}\]])/g, '$1');
    const opts = JSON.parse(text).compilerOptions ?? {};
    const base = join(root, opts.baseUrl ?? '.');
    const out: Record<string, string> = {};
    for (const [key, targets] of Object.entries<string[]>(opts.paths ?? {})) {
      if (!targets?.[0]) continue;
      out[key.replace(/\/\*$/, '')] = join(base, targets[0].replace(/\/\*$/, ''));
    }
    return out;
  } catch {
    return {};
  }
}

export function generateUnit(a: Analysis, plan: Plan, p: Paths): { files: GeneratedFile[]; contents: Map<string, string> } {
  const enabled = new Set(plan.targets.filter((t) => t.type === 'unit' && t.enabled).map((t) => t.target));
  const byFile = new Map<string, FunctionInfo[]>();
  for (const f of a.functions) {
    if (!enabled.has(f.id)) continue;
    byFile.set(f.file, [...(byFile.get(f.file) ?? []), f]);
  }

  const contents = new Map<string, string>();
  const files: GeneratedFile[] = [];
  if (byFile.size === 0) return { files, contents };

  const helperPath = join(p.unitDir, '_repeval.ts');
  contents.set(helperPath, HELPER);
  files.push({ path: rel(p.root, helperPath), kind: 'helper', framework: 'vitest', targets: [] });

  for (const [source, fns] of byFile) {
    const testPath = join(p.unitDir, testFileName(source));
    const needsRun = fns.some((f) => f.callable);
    const body = [
      `// Generated by Repeval ${VERSION} (template writer, no AI).`,
      `// Source: ${source}`,
      `// Baseline tests record what each function returns today, then flag any change on later runs.`,
      `import { describe, expect, it } from 'vitest';`,
      needsRun ? `import { matchBaseline, run } from './_repeval';` : '',
      `import * as mod from ${q(importPath(p.unitDir, join(p.root, source)))};`,
      '',
      `describe(${q(source)}, () => {`,
      `  it('loads without errors', () => {`,
      `    expect(typeof mod).toBe('object');`,
      `  });`,
      '',
      fns.map(functionBlock).join('\n\n'),
      `});`,
      '',
    ]
      .filter((l, i, arr) => !(l === '' && arr[i - 1] === ''))
      .join('\n');
    contents.set(testPath, body);
    files.push({ path: rel(p.root, testPath), kind: 'unit', framework: 'vitest', targets: fns.map((f) => `unit:${f.id}`) });
  }

  const config = `// Generated by Repeval ${VERSION}. Runs only the tests in .repeval/tests/unit.
export default {
  test: {
    include: ['.repeval/tests/unit/**/*.test.ts'],
    environment: 'node',
    reporters: ['default', 'json'],
    outputFile: { json: '.repeval/results/unit.json' },
    passWithNoTests: true,
    testTimeout: 10000,
  },
  resolve: { alias: ${JSON.stringify(tsconfigAliases(p.root), null, 2).replace(/\n/g, '\n  ')} },
};
`;
  contents.set(p.vitestConfig, config);
  files.push({ path: rel(p.root, p.vitestConfig), kind: 'config', framework: 'vitest', targets: [] });
  return { files, contents };
}
