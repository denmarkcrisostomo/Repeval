// The workflow file users add to their repo. Kept identical to templates/repeval.yml in the CLI
// (scripts/check-workflow.mjs fails the build if the two drift apart).
export const WORKFLOW_PATH = '.github/workflows/repeval.yml';
export const WORKFLOW_FILE = 'repeval.yml';
export const ARTIFACT_NAME = 'repeval-report';
/** The workflow's name. Bump the version here and in templates/repeval.yml when the file changes. */
export const WORKFLOW_NAME = 'Repeval (workflow v2)';
/** run-name of the save-tests runs, so they can be left out of the run history. */
export const SAVE_RUN_TITLE = 'Save Repeval tests to a branch';
export const TESTS_BRANCH = 'repeval-tests';

export const WORKFLOW_YAML = `# .github/workflows/repeval.yml
# Repeval generates and runs tests for this repo.
# It only runs when you start it (from the Actions tab or the Repeval website).
# "repeval@0.1" picks up bug-fix releases by itself. The "v2" in the name tells the
# Repeval website which version of this file the repo has, so it can offer updates.
name: Repeval (workflow v2)
run-name: \${{ inputs.save_from_run && 'Save Repeval tests to a branch' || 'Repeval' }}

on:
  workflow_dispatch:
    inputs:
      ai:
        description: AI provider
        type: choice
        options: [none, anthropic, openai]
        default: none
      tests:
        description: Which tests
        type: choice
        options: [all, unit, e2e, load]
        default: all
      save_from_run:
        description: Leave empty to run tests. The Repeval website fills in a run id to push that run's tests to the repeval-tests branch.
        type: string
        default: ''

permissions:
  contents: read

concurrency:
  group: repeval-\${{ inputs.save_from_run && 'save' || 'run' }}
  cancel-in-progress: true

jobs:
  repeval:
    if: \${{ !inputs.save_from_run }}
    runs-on: ubuntu-latest
    timeout-minutes: 30
    steps:
      - name: Checkout
        uses: actions/checkout@v4
        with:
          persist-credentials: false

      - name: Set up Node
        uses: actions/setup-node@v4
        with:
          node-version: 22

      - name: Analyze
        run: npx --yes repeval@0.1 analyze

      - name: Plan
        run: npx --yes repeval@0.1 plan --tests "$TESTS"
        env:
          TESTS: \${{ inputs.tests }}

      - name: Generate
        run: npx --yes repeval@0.1 generate --ai "$AI"
        env:
          AI: \${{ inputs.ai }}
          ANTHROPIC_API_KEY: \${{ secrets.ANTHROPIC_API_KEY }}
          OPENAI_API_KEY: \${{ secrets.OPENAI_API_KEY }}

      - name: Test
        run: npx --yes repeval@0.1 test
        env:
          AI: \${{ inputs.ai }}
          ANTHROPIC_API_KEY: \${{ secrets.ANTHROPIC_API_KEY }}
          OPENAI_API_KEY: \${{ secrets.OPENAI_API_KEY }}

      - name: Save report
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: repeval-report
          path: repeval-report/
          include-hidden-files: false
          retention-days: 7

  # Only when you press "Commit to a branch" on the report: pushes that run's generated tests
  # to the repeval-tests branch, using this repo's own token. Nothing else gets write access.
  save-tests:
    if: \${{ inputs.save_from_run }}
    runs-on: ubuntu-latest
    timeout-minutes: 10
    permissions:
      contents: write
      actions: read
    steps:
      - name: Check the run id
        run: '[[ "$RUN_ID" =~ ^[0-9]+$ ]] || { echo "save_from_run must be a run id"; exit 1; }'
        env:
          RUN_ID: \${{ inputs.save_from_run }}

      - name: Check out the repo
        uses: actions/checkout@v4

      - name: Get the tests from that run
        uses: actions/download-artifact@v4
        with:
          name: repeval-report
          run-id: \${{ inputs.save_from_run }}
          github-token: \${{ github.token }}
          path: \${{ runner.temp }}/report

      - name: Push the repeval-tests branch
        run: |
          test -d "$REPORT/generated" || { echo "That run wrote no test files."; exit 1; }
          git switch -C repeval-tests
          mkdir -p .repeval
          cp -R "$REPORT/generated/." .repeval/
          git add -f .repeval
          if git diff --cached --quiet; then
            echo "These tests are already on the default branch."
          else
            git -c user.name="github-actions[bot]" -c user.email="41898208+github-actions[bot]@users.noreply.github.com" \
              commit -m "Add tests generated by Repeval" -m "From run $RUN_ID. Run them with: npx vitest run --config .repeval/vitest.config.mjs"
          fi
          git push --force origin repeval-tests
        env:
          REPORT: \${{ runner.temp }}/report
          RUN_ID: \${{ inputs.save_from_run }}
`;

/** GitHub's own "new file" page with the workflow filled in. The user reads it and commits it themselves. */
export function newFileUrl(owner: string, repo: string, branch: string): string {
  const q = new URLSearchParams({ filename: WORKFLOW_PATH, value: WORKFLOW_YAML });
  return `https://github.com/${encodeURIComponent(owner)}/${encodeURIComponent(repo)}/new/${encodeURIComponent(branch)}?${q}`;
}

/** GitHub's editor for the existing workflow file, for updating it to the current version. */
export function editFileUrl(owner: string, repo: string, branch: string): string {
  return `https://github.com/${encodeURIComponent(owner)}/${encodeURIComponent(repo)}/edit/${encodeURIComponent(branch)}/${WORKFLOW_PATH}`;
}

/** GitHub's "open a pull request" page for the repeval-tests branch, with a title and description filled in. */
export function testsPullRequestUrl(owner: string, repo: string, branch: string): string {
  const q = new URLSearchParams({
    expand: '1',
    title: 'Add tests generated by Repeval',
    body: [
      'Tests written by [Repeval](https://github.com/denmarkcrisostomo/Repeval) for this repo.',
      '',
      '- Unit tests: `npx vitest run --config .repeval/vitest.config.mjs`',
      '- Page and API tests: see `.repeval/e2e/playwright.config.ts`',
      '',
      'Baseline tests record what each function returns on their first run, then flag any change.',
    ].join('\n'),
  });
  return `https://github.com/${encodeURIComponent(owner)}/${encodeURIComponent(repo)}/compare/${encodeURIComponent(branch)}...${TESTS_BRANCH}?${q}`;
}
